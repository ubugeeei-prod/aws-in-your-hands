-- The database being left, as it was found: everything in `public`.
CREATE TABLE public.owners (
  owner text PRIMARY KEY,
  note_count integer NOT NULL CHECK (note_count >= 0)
);

CREATE TABLE public.notes (
  id uuid PRIMARY KEY,
  owner text NOT NULL REFERENCES public.owners (owner),
  title text NOT NULL CHECK (char_length(title) BETWEEN 1 AND 120),
  body text NOT NULL CHECK (char_length(body) <= 10000),
  version integer NOT NULL CHECK (version >= 1),
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL
);

CREATE INDEX notes_owner_created_idx ON public.notes (owner, created_at, id);

-- Numbered by the database. The sequence behind `id` is state that no row carries.
CREATE TABLE public.note_revisions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  note_id uuid NOT NULL,
  version integer NOT NULL,
  title text NOT NULL,
  saved_at timestamptz NOT NULL
);

-- Append-only, and nobody gave it a key.
CREATE TABLE public.audit_log (
  at timestamptz NOT NULL,
  actor text NOT NULL,
  action text NOT NULL
);

-- The migration runner's own bookkeeping. It describes this database, not the next one.
CREATE TABLE public.aih_migrations (
  name text PRIMARY KEY,
  applied_at timestamptz NOT NULL
);
