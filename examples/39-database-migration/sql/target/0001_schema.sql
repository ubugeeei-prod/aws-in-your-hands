-- The target is created by hand, in full, before any row arrives: DMS would
-- create tables and primary keys only, and none of the rest.
CREATE SCHEMA IF NOT EXISTS app;

CREATE TABLE app.owners (
  owner varchar(128) PRIMARY KEY,
  note_count integer NOT NULL CHECK (note_count >= 0)
);

CREATE TABLE app.notes (
  id uuid PRIMARY KEY,
  owner varchar(128) NOT NULL REFERENCES app.owners (owner),
  title text NOT NULL CHECK (char_length(title) BETWEEN 1 AND 120),
  body text NOT NULL CHECK (char_length(body) <= 10000),
  version integer NOT NULL CHECK (version >= 1),
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL
);

CREATE INDEX notes_owner_created_idx ON app.notes (owner, created_at, id);

CREATE TABLE app.note_revisions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  note_id uuid NOT NULL,
  version integer NOT NULL,
  title text NOT NULL,
  saved_at timestamptz NOT NULL
);

CREATE TABLE app.audit_log (
  at timestamptz NOT NULL,
  actor text NOT NULL,
  action text NOT NULL,
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);
